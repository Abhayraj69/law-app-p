const db = require('../db');

/**
 * Task Service
 *
 * Backs the task list (both manually-created tasks and the reminder
 * engine's output — see reminderEngine.js) and the dashboard's "awaiting
 * draft" count. Role floor for every route here is PARALEGAL — same
 * reasoning as time tracking (server/services/timeEntryService.js):
 * managing your own routine follow-up work is not a privileged action.
 * There is no per-user ownership restriction on READS the way time entries
 * have one for PARALEGAL — a task list is meant to be seen firm-wide (who's
 * behind on what), matching how case_deadlines/hearings already behave.
 */

const VALID_TASK_TYPES = ['general', 'draft_needed', 'follow_up', 'reminder'];
const VALID_STATUSES = ['open', 'in_progress', 'done', 'dismissed'];

function notFound() {
  const err = new Error('Task not found.');
  err.status = 404;
  return err;
}

function badRequest(message, code) {
  const err = new Error(message);
  err.status = 400;
  if (code) err.code = code;
  return err;
}

function toTaskView(row) {
  const today = new Date().toISOString().slice(0, 10);
  return {
    id: row.id,
    case_id: row.case_id,
    case_name: row.case_name,
    hearing_id: row.hearing_id,
    title: row.title,
    description: row.description,
    task_type: row.task_type,
    due_date: row.due_date,
    // Computed, not stored: "overdue" is only ever true relative to today,
    // at read time — the same reasoning time_entries' amount_cents is
    // deliberately NOT persisted (see toTimeEntryView). This is the
    // reminder engine's actual "reminder" surface: nothing pushes a
    // notification, a task simply reads as overdue once its due_date has
    // passed while still open.
    overdue: !!(row.due_date && row.due_date < today && row.status === 'open'),
    status: row.status,
    assigned_to_user_id: row.assigned_to_user_id,
    assigned_to_name: row.assigned_to_name,
    created_by_user_id: row.created_by_user_id,
    created_by_name: row.created_by_name,
    auto_generated: row.auto_generated,
    created_at: row.created_at,
    updated_at: row.updated_at
  };
}

function validateTaskType(taskType) {
  if (taskType !== undefined && !VALID_TASK_TYPES.includes(taskType)) {
    throw badRequest(`task_type must be one of: ${VALID_TASK_TYPES.join(', ')}.`);
  }
  return taskType;
}

function validateStatus(status) {
  if (status !== undefined && !VALID_STATUSES.includes(status)) {
    throw badRequest(`status must be one of: ${VALID_STATUSES.join(', ')}.`);
  }
  return status;
}

function validateTitle(title) {
  if (!title || !String(title).trim()) {
    throw badRequest('title is required.');
  }
  return String(title).trim();
}

class TaskService {
  /** GET /api/v1/tasks — optionally filtered by case, status, assignee, type. */
  static async listTasks(tenantId, filters = {}) {
    const { case_id, status, assigned_to_user_id, task_type } = filters;
    validateStatus(status);
    validateTaskType(task_type);
    const rows = await db.listTasksForFirm(tenantId, {
      caseId: case_id, status, assignedToUserId: assigned_to_user_id, taskType: task_type
    });
    return rows.map(toTaskView);
  }

  /** POST /api/v1/tasks — a manually-created task. */
  static async createTask(tenantId, actingUser, payload = {}) {
    const { case_id, hearing_id, title, description, task_type, due_date, assigned_to_user_id } = payload;
    validateTaskType(task_type);

    const row = await db.insertTask({
      firmId: tenantId,
      caseId: case_id || null,
      hearingId: hearing_id || null,
      title: validateTitle(title),
      description: description || null,
      taskType: task_type || 'general',
      dueDate: due_date || null,
      assignedToUserId: assigned_to_user_id || null,
      createdByUserId: actingUser.id,
      autoGenerated: false
    });

    await db.insertAuditLog({
      firmId: tenantId, userId: actingUser.id, action: 'CREATE_TASK',
      details: { task_id: row.id, title: row.title, task_type: row.task_type }
    });

    return toTaskView(row);
  }

  /**
   * Used only by the reminder engine (HearingService.logHearingUpdate),
   * never directly by a route. Idempotent per (hearing_id, task_type): if
   * an open auto-generated task of this type already exists for this
   * hearing, its due date is refreshed in place instead of spawning a
   * duplicate — an associate correcting a typo in an already-logged
   * update must not multiply the task list every time they save.
   */
  static async createAutoTask(tenantId, spec) {
    const existing = spec.hearing_id
      ? await db.findOpenAutoTaskForHearing(tenantId, spec.hearing_id, spec.task_type)
      : null;

    if (existing) {
      return db.updateTaskFields(tenantId, existing.id, {
        dueDate: spec.due_date || null,
        description: spec.description || null
      });
    }

    const row = await db.insertTask({
      firmId: tenantId,
      caseId: spec.case_id || null,
      hearingId: spec.hearing_id || null,
      title: spec.title,
      description: spec.description || null,
      taskType: spec.task_type,
      dueDate: spec.due_date || null,
      assignedToUserId: null,
      createdByUserId: null,
      autoGenerated: true
    });

    await db.insertAuditLog({
      firmId: tenantId, userId: null, action: 'CREATE_TASK',
      details: { task_id: row.id, title: row.title, task_type: row.task_type, auto_generated: true, hearing_id: spec.hearing_id || null }
    });

    return row;
  }

  /** PATCH /api/v1/tasks/:id */
  static async updateTask(tenantId, actingUser, taskId, payload = {}) {
    const existing = await db.getTaskById(tenantId, taskId);
    if (!existing) throw notFound();

    validateTaskType(payload.task_type);
    validateStatus(payload.status);

    const updates = {};
    if (payload.title !== undefined) updates.title = validateTitle(payload.title);
    if (payload.description !== undefined) updates.description = payload.description;
    if (payload.task_type !== undefined) updates.taskType = payload.task_type;
    if (payload.due_date !== undefined) updates.dueDate = payload.due_date;
    if (payload.status !== undefined) updates.status = payload.status;
    if (payload.assigned_to_user_id !== undefined) updates.assignedToUserId = payload.assigned_to_user_id;

    const row = await db.updateTaskFields(tenantId, taskId, updates);

    await db.insertAuditLog({
      firmId: tenantId, userId: actingUser.id, action: 'UPDATE_TASK',
      details: { task_id: taskId, updates: payload }
    });

    return toTaskView(row);
  }

  /** DELETE /api/v1/tasks/:id */
  static async deleteTask(tenantId, actingUser, taskId) {
    const existing = await db.getTaskById(tenantId, taskId);
    if (!existing) throw notFound();

    await db.deleteTaskRow(tenantId, taskId);

    await db.insertAuditLog({
      firmId: tenantId, userId: actingUser.id, action: 'DELETE_TASK',
      details: { task_id: taskId, title: existing.title }
    });

    return { deleted: true };
  }
}

module.exports = TaskService;
